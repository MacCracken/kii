#!/usr/bin/env bash
# gen-shape-table.sh — generate src/ascii_shape.cyr, the ASCII lane's glyph
# coverage table.
#
# Each glyph is rasterized white on black in a 24x48 cell (Liberation Mono
# Regular, 40 px: the advance is exactly 24 px, and the 45 px line box, ascent
# 34 + descent 13, sits on a baseline at y = 35, 1 px below the top). The cell
# is split into kii's 2x3 regions of 12x16 px, row-major: r0c0 r0c1 r1c0 r1c1
# r2c0 r2c1. A region's value is its summed ink, scaled PER ROW so the glyph with
# the most ink in either region of that row reads 255:
#
#     value = floor((sum * 255 * 2 + max_sum[row]) / (2 * max_sum[row]))   (round half up)
#
# Scaling each dimension apart is Alex Harri's normalization (see src/ascii.cyr):
# without it most glyphs carry little ink in the top and bottom rows, so their
# vectors crowd one corner of the space and a bright top or bottom region has no
# glyph near it. kii shares one maximum between a row's two regions, where Harri
# scales each region alone, because the left and right maxima come from
# asymmetric glyphs (% and @): scaled apart, a symmetric glyph such as `.` would
# read heavier on one side, and the mirrored pairs / \, ( ), < > would stop being
# mirrors. Either way 0..255 runs from "no ink" to "the most ink any glyph has
# there", on the scale of the cell luminance it is matched against (src/ascii.cyr,
# _ascii_match). The arithmetic is integer, so only the rasterizer can move a
# value; the header records the font, ImageMagick and FreeType that produced the
# committed file.
#
#   ./scripts/gen-shape-table.sh > src/ascii_shape.cyr   # regenerate
#   ./scripts/gen-shape-table.sh --check                  # exit 1 if it differs
#
# Needs `magick` (ImageMagick 7) and the Liberation Mono font. The glyph set and
# its order are fixed here: _ascii_match breaks a tie toward the lower index, so
# reordering the list changes output.

set -euo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"
FONT="${KII_SHAPE_FONT:-/usr/share/fonts/liberation/LiberationMono-Regular.ttf}"
OUT="$REPO/src/ascii_shape.cyr"

# The 27 glyphs, by code point: space . , ' ` : ; - _ ~ = + | / \ < > ( ) ^ v x o * # % @
GLYPHS=(32 46 44 39 96 58 59 45 95 126 61 43 124 47 92 60 62 40 41 94 118 120 111 42 35 37 64)

command -v magick >/dev/null || { echo "gen-shape-table: magick (ImageMagick 7) not found" >&2; exit 2; }
[ -r "$FONT" ] || { echo "gen-shape-table: font not readable: $FONT (set KII_SHAPE_FONT)" >&2; exit 2; }

generate() {
    local tmp
    tmp="$(mktemp -d)"
    trap 'rm -rf "$tmp"' RETURN
    local cp
    for cp in "${GLYPHS[@]}"; do
        # Text from a file (`@path`), so % \ and @ are drawn rather than read as
        # escapes or a filename.
        printf "\\$(printf '%03o' "$cp")" > "$tmp/glyph.txt"
        magick -size 24x48 xc:black -font "$FONT" -pointsize 40 -fill white \
            -annotate +0+35 "@$tmp/glyph.txt" -depth 8 "gray:$tmp/$cp.raw"
    done
    local im ft fh h
    im="$(magick -version | sed -n 's/^Version: ImageMagick \([^ ]*\).*/\1/p')"
    # FreeType's release, from its header where one is installed.
    ft="unknown"
    h=/usr/include/freetype2/freetype/freetype.h
    if [ -r "$h" ]; then
        ft="$(awk '/#define FREETYPE_(MAJOR|MINOR|PATCH)/ { v = v (v == "" ? "" : ".") $3 } END { print v }' "$h")"
    fi
    fh="$(sha256sum "$FONT" | cut -c1-16)"
    for cp in "${GLYPHS[@]}"; do
        printf '%s ' "$cp"
        od -An -v -tu1 "$tmp/$cp.raw" | tr -s ' \n' '\n\n' | sed '/^$/d' | awk '
            { x = (NR - 1) % 24; y = int((NR - 1) / 24); s[int(y / 16) * 2 + int(x / 12)] += $1 }
            END { if (NR != 24 * 48) { exit 1 }; printf "%d %d %d %d %d %d\n", s[0], s[1], s[2], s[3], s[4], s[5] }'
    done | awk -v im="$im" -v ft="$ft" -v font="$(basename "$FONT")" -v fh="$fh" '
        { cp[NR] = $1; for (d = 0; d < 6; d++) { s[NR, d] = $(d + 2); r = int(d / 2); if ($(d + 2) > max[r]) max[r] = $(d + 2) } }
        END {
            n = NR
            print "# ascii_shape.cyr — the ASCII lane'"'"'s glyph coverage table."
            print "#"
            print "# === GENERATED by scripts/gen-shape-table.sh — do not hand-edit ==="
            printf "# %s (sha256 %s...), 40 px in a 24x48 cell, baseline y = 35;\n", font, fh
            print "# 2x3 regions of 12x16 px; each value is the region'"'"'s ink, scaled per row"
            print "# so the glyph with the most ink in that row reads 255."
            printf "# Rasterized with ImageMagick %s, FreeType %s.\n", im, ft
            print "#"
            print "# ASCII_SHAPE_GLYPHS[g] is glyph g'"'"'s byte; ASCII_SHAPE_COV[g * 6 + k] is its"
            print "# coverage in region k (row-major r0c0 r0c1 r1c0 r1c1 r2c0 r2c1, 0..255)."
            print ""
            printf "var ASCII_SHAPE_COUNT = %d;\n", n
            printf "var ASCII_SHAPE_GLYPHS[%d];\n", 32
            printf "var ASCII_SHAPE_COV[%d];\n", 192
            print "var _ascii_shape_inited = 0;"
            print ""
            print "# Populate the glyph + coverage tables (idempotent; mirrors palette_init)."
            print "fn _ascii_shape_init(): i64 {"
            print "    if (_ascii_shape_inited == 1) { return 0; }"
            for (g = 1; g <= n; g++) {
                printf "    store64(&ASCII_SHAPE_GLYPHS + %d * 8, %d);\n", g - 1, cp[g]
                for (d = 0; d < 6; d++) {
                    r = int(d / 2)
                    v = int((s[g, d] * 255 * 2 + max[r]) / (2 * max[r]))
                    printf "    store64(&ASCII_SHAPE_COV + (%d * 6 + %d) * 8, %d);\n", g - 1, d, v
                }
            }
            print "    _ascii_shape_inited = 1;"
            print "    return 0;"
            print "}"
        }'
}

if [ "${1:-}" = "--check" ]; then
    if generate | cmp -s - "$OUT"; then
        echo "gen-shape-table: src/ascii_shape.cyr is current"
    else
        echo "gen-shape-table: src/ascii_shape.cyr differs from a fresh generation" >&2
        generate | diff "$OUT" - >&2 || true
        exit 1
    fi
else
    generate
fi
